// Rebuilds scripts/selection-more.txt from the translated names in scripts/ru/10-more-*.json
// (every translated key is added to the base; stretches go to the stretch category, held per side).
// Usage: node scripts/gen-selection-more.mjs
import { readFile, readdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const files = (await readdir(new URL('scripts/ru/', root))).filter((f) => f.startsWith('10-more-')).sort();
const names = [];
for (const f of files) names.push(...Object.keys(JSON.parse(await readFile(new URL(`scripts/ru/${f}`, root), 'utf8'))));

const stretch = names.filter((n) => /stretch/.test(n));
const rest = names.filter((n) => !/stretch/.test(n));
const out = ['# Generated by scripts/gen-selection-more.mjs, do not edit', '# == more', ...rest, '# == stretch more', ...stretch.map((n) => `${n} | side`), ''];
await writeFile(new URL('scripts/selection-more.txt', root), out.join('\n'));
console.log(`selection-more: ${rest.length} + ${stretch.length} stretches`);
